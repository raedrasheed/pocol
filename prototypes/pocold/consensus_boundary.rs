/// The source with comments blanked (strings and attributes kept), so doc text never counts as a reference.
pub fn strip_comments(s: &str) -> String {
    let c: Vec<char> = s.chars().collect();
    let (mut out, mut i) = (String::with_capacity(s.len()), 0);
    let ident = |ch: char| ch.is_alphanumeric() || ch == '_';
    while i < c.len() {
        if c[i] == '/' && c.get(i + 1) == Some(&'/') {
            while i < c.len() && c[i] != '\n' { i += 1 }
        } else if c[i] == '/' && c.get(i + 1) == Some(&'*') {
            let mut depth = 0;
            while i < c.len() {
                if c[i] == '/' && c.get(i + 1) == Some(&'*') { depth += 1; i += 2 } else if c[i] == '*' && c.get(i + 1) == Some(&'/') { depth -= 1; i += 2; if depth == 0 { break } } else { if c[i] == '\n' { out.push('\n') } i += 1 }
            }
        } else if c[i] == 'r' && (i == 0 || !ident(c[i - 1]) || c[i - 1] == 'b') && matches!(c.get(i + 1), Some('"') | Some('#')) {
            let mut j = i + 1; let mut hashes = 0;
            while c.get(j) == Some(&'#') { hashes += 1; j += 1 }
            if c.get(j) != Some(&'"') { out.push(c[i]); i += 1; continue }
            out.extend(&c[i..=j]); j += 1;
            while j < c.len() && !(c[j] == '"' && (0..hashes).all(|k| c.get(j + 1 + k) == Some(&'#'))) { out.push(c[j]); j += 1 }
            let end = (j + 1 + hashes).min(c.len()); out.extend(&c[j.min(c.len())..end]); i = end;
        } else if c[i] == '"' {
            out.push('"'); i += 1;
            while i < c.len() && c[i] != '"' { if c[i] == '\\' { out.push(c[i]); i += 1 } if i < c.len() { out.push(c[i]); i += 1 } }
            if i < c.len() { out.push('"'); i += 1 }
        } else if c[i] == '\'' {
            // A char literal ('x', '\n', '"') is copied whole; anything else is a lifetime.
            if c.get(i + 1) == Some(&'\\') { let mut j = i + 3; while j < c.len() && c[j] != '\'' { j += 1 } out.extend(&c[i..(j + 1).min(c.len())]); i = j + 1 }
            else if c.get(i + 2) == Some(&'\'') { out.extend(&c[i..i + 3]); i += 3 }
            else { out.push('\''); i += 1 }
        } else { out.push(c[i]); i += 1 }
    }
    out
}
fn is_ident(ch: char) -> bool { ch.is_ascii_alphanumeric() || ch == '_' }
fn ident_at(s: &str, i: usize) -> &str { let e = s[i..].find(|c: char| !is_ident(c)).map_or(s.len(), |k| i + k); &s[i..e] }

/// A `mod` declaration: name, `#[path]` value, whether `#[cfg(test)]` gates it, and an inline body's byte range.
#[derive(Clone, Debug)]
pub struct ModDecl { pub name: String, pub path: Option<String>, pub test: bool, pub inline: bool, pub body: (usize, usize) }
pub fn mod_decls(src: &str) -> Vec<ModDecl> { decls_in(&strip_comments(src)) }
/// The index just past the `}` matching the `{` at `open`, skipping string, raw string and char literals.
fn block_end(s: &str, open: usize) -> usize {
    let c = s.as_bytes();
    let (mut i, mut depth) = (open, 0usize);
    while i < c.len() {
        match c[i] {
            b'{' => depth += 1,
            b'}' => { depth -= 1; if depth == 0 { return i + 1 } }
            b'"' => { i += 1; while i < c.len() && c[i] != b'"' { if c[i] == b'\\' { i += 1 } i += 1 } }
            b'r' if (i == 0 || !is_ident(c[i - 1] as char) || c[i - 1] == b'b') && matches!(c.get(i + 1), Some(b'#') | Some(b'"')) => {
                let mut j = i + 1; let mut h = 0;
                while c.get(j) == Some(&b'#') { h += 1; j += 1 }
                if c.get(j) == Some(&b'"') {
                    j += 1;
                    while j < c.len() && !(c[j] == b'"' && (0..h).all(|k| c.get(j + 1 + k) == Some(&b'#'))) { j += 1 }
                    i = j + h;
                }
            }
            b'\'' => { if c.get(i + 1) == Some(&b'\\') { i += 3; while i < c.len() && c[i] != b'\'' { i += 1 } } else if c.get(i + 2) == Some(&b'\'') { i += 2 } }
            _ => {}
        }
        i += 1;
    }
    c.len()
}
fn decls_in(s: &str) -> Vec<ModDecl> {
    let mut out = Vec::new();
    let mut from = 0;
    while let Some(k) = s[from..].find("mod") {
        let i = from + k; from = i + 3;
        if (i > 0 && is_ident(s[..i].chars().last().unwrap())) || !s[i + 3..].starts_with(|c: char| c.is_whitespace()) { continue }
        let rest = s[i + 3..].trim_start(); let name = ident_at(rest, 0);
        if name.is_empty() { continue }
        let after = rest[name.len()..].trim_start();
        let inline = after.starts_with('{');
        if !inline && !after.starts_with(';') { continue }
        // Attributes of this item: back to the previous statement or block boundary.
        let start = s[..i].rfind(|c| c == ';' || c == '}' || c == '{').map_or(0, |p| p + 1);
        let attrs = &s[start..i];
        let path = attrs.find("#[path").and_then(|p| { let a = &attrs[p..]; let q = a.find('"')? + 1; let e = a[q..].find('"')?; Some(a[q..q + e].to_string()) });
        let open = s.len() - after.len();
        let body = if inline { (open, block_end(s, open)) } else { (open, open) };
        out.push(ModDecl { name: name.to_string(), path, test: attrs.contains("#[cfg(test)]"), inline, body });
    }
    out
}
fn parent_dir(p: &str) -> &str { p.rfind('/').map_or("", |i| &p[..=i]) }
fn normalize(p: &str) -> Option<String> {
    let mut parts: Vec<&str> = Vec::new();
    for c in p.split('/') { match c { "" | "." => {} ".." => { parts.pop()?; } x => parts.push(x) } }
    Some(parts.join("/"))
}
/// The file a non-inline `mod` in `parent` loads, by the reference's rules (`#[path]` relative to the parent's
/// directory; otherwise `name.rs` or `name/mod.rs` beside a mod-rs parent, or under the parent's stem).
fn mod_file(root: &Path, parent: &str, d: &ModDecl) -> Option<String> {
    if let Some(p) = &d.path { return normalize(&format!("{}{p}", parent_dir(parent))) }
    let file = parent.rsplit('/').next().unwrap_or(parent);
    let base = if ["lib.rs", "mod.rs", "main.rs"].contains(&file) { parent_dir(parent).to_string() } else { format!("{}/", parent.trim_end_matches(".rs")) };
    [format!("{base}{}.rs", d.name), format!("{base}{}/mod.rs", d.name)].into_iter().find(|c| root.join(c).is_file())
}
/// Guard check 7: a `-*suffix` file is excluded only when every declaration of it is `#[cfg(test)]`.
fn declared_only_under_cfg_test(root: &Path, path: &str) -> Result<(), String> {
    let dir = parent_dir(path);
    let mut parents = vec![format!("{dir}mod.rs"), format!("{dir}lib.rs")];
    if let Some(up) = dir.strip_suffix('/') { parents.push(format!("{up}.rs")) }
    let mut seen = 0;
    for p in parents.iter().filter(|p| root.join(p).is_file()) {
        let src = std::fs::read_to_string(root.join(p)).map_err(|e| format!("{p}: {e}"))?;
        for d in mod_decls(&src).iter().filter(|d| !d.inline && mod_file(root, p, d).as_deref() == Some(path)) {
            if !d.test { return Err(format!("{p} declares it without #[cfg(test)]")) }
            seen += 1;
        }
    }
    if seen == 0 { return Err("no parent declares it through a #[cfg(test)] mod".into()) }
    Ok(())
}
/// Names a source refers to in `crate` (and, for a crate-root module file, `super`) and in extern crates.
/// Returns (target crate, top-level name). `*` stands for a glob import.
pub fn references(src: &str, own: &str, depth: usize, own_mods: &BTreeSet<String>) -> Vec<(String, String)> {
    // Test-only inline modules are not consensus: their bodies are blanked. In any other inline module `super::`
    // names the file's own module, so it is a crate reference only outside inline bodies.
    let mut s = strip_comments(src);
    let decls = decls_in(&s);
    for d in decls.iter().filter(|d| d.inline && d.test) { s.replace_range(d.body.0..d.body.1, &" ".repeat(d.body.1 - d.body.0)) }
    let inner: Vec<(usize, usize)> = decls.iter().filter(|d| d.inline && !d.test).map(|d| d.body).collect();
    let mut out = Vec::new();
    let mut prefixes: Vec<(String, String)> = vec![("crate::".into(), own.into())];
    if depth == 1 { prefixes.push(("super::".into(), own.into())) }
    for (c, _, ext) in CRATES { if c != own { prefixes.push((format!("{ext}::"), c.into())) } }
    for (prefix, target) in &prefixes {
        let mut from = 0;
        while let Some(k) = s[from..].find(prefix.as_str()) {
            let i = from + k; from = i + prefix.len();
            if i > 0 { let p = s[..i].chars().last().unwrap(); if is_ident(p) || p == '$' || p == ':' { continue } }
            if prefix == "super::" && inner.iter().any(|&(a, b)| a < i && i < b) { continue }
            for n in group_heads(&s[from..]) { out.push((target.clone(), n)) }
        }
    }
    if depth == 0 {
        // The crate root names its own modules without a prefix (`net::MAX_FRAME`).
        let mut from = 0;
        while let Some(k) = s[from..].find("::") {
            let i = from + k; from = i + 2;
            let st = s[..i].rfind(|c: char| !is_ident(c)).map_or(0, |p| p + 1);
            let name = &s[st..i];
            if name.is_empty() || !own_mods.contains(name) { continue }
            if st > 0 { let p = s[..st].chars().last().unwrap(); if p == ':' || p == '$' { continue } }
            out.push((own.into(), name.into()));
        }
    }
    out.sort(); out.dedup(); out
}
/// The top-level names of `x` or `{a::b, c, d::{e}}` at the start of `s`.
fn group_heads(s: &str) -> Vec<String> {
    let s = s.trim_start();
    if s.starts_with('*') { return vec!["*".into()] }
    if !s.starts_with('{') { let n = ident_at(s, 0); return if n.is_empty() || n == "self" { vec![] } else { vec![n.into()] } }
    let (mut depth, mut item, mut out) = (0, String::new(), Vec::new());
    for ch in s.chars() {
        match ch { '{' => { depth += 1; if depth == 1 { continue } } '}' => { depth -= 1; if depth == 0 { break } } _ => {} }
        if depth == 1 && ch == ',' { out.push(std::mem::take(&mut item)) } else { item.push(ch) }
    }
    out.push(item);
    out.into_iter().filter_map(|i| { let i = i.trim(); if i.starts_with('*') { return Some("*".into()) } let n = ident_at(i, 0); (!n.is_empty() && n != "self").then(|| n.to_string()) }).collect()
}
#[derive(Clone, Debug, PartialEq)]
enum Class { Plus, Inline, Local, Excluded }
/// Guard checks 5 and 6: every crate-root module is classified, every module a `+` file loads is `+` (or
/// test-only), and a `+` file refers into a `=`/`-` module only through a `~` allowance.
fn modules(root: &Path, b: &Boundary, files: &BTreeMap<String, Vec<u8>>, test_only: &BTreeSet<String>) -> Vec<String> {
    let mut problems = Vec::new();
    let mut tables: BTreeMap<String, BTreeMap<String, Class>> = BTreeMap::new();
    let mut visit: Vec<(String, String, usize)> = Vec::new();
    for (c, lib, _) in CRATES {
        if !files.contains_key(lib) { problems.push(format!("crate root {lib} is not in the boundary")); continue }
        visit.push((lib.to_string(), c.to_string(), 0));
    }
    let mut seen = BTreeSet::new();
    let mut checked: Vec<(String, String, usize)> = Vec::new();
    while let Some((file, krate, depth)) = visit.pop() {
        if !seen.insert((file.clone(), krate.clone())) { continue }
        checked.push((file.clone(), krate.clone(), depth));
        let src = String::from_utf8_lossy(&files[&file]).into_owned();
        for d in mod_decls(&src) {
            let qualified = format!("{krate}::{}", d.name);
            let class = if d.inline { Class::Inline } else if depth == 0 && b.local.contains(&qualified) { Class::Local } else {
                match mod_file(root, &file, &d) {
                    Some(f) if files.contains_key(&f) => { if f.ends_with(".rs") { visit.push((f, krate.clone(), depth + 1)) } Class::Plus }
                    Some(f) if test_only.contains(&f) || b.exclude.iter().any(|x| covers(x, &f)) => Class::Excluded,
                    Some(f) => { problems.push(format!("classify module {qualified} ({file} loads {f}): add +{f}, -{f} or ={qualified} to {BOUNDARY_FILE}")); Class::Excluded }
                    None => { problems.push(format!("classify module {qualified}: {file} declares it but no file exists")); Class::Excluded }
                }
            };
            if depth == 0 { tables.entry(krate.clone()).or_default().insert(d.name.clone(), class); }
        }
    }
    for l in &b.local {
        let (c, n) = l.split_once("::").unwrap();
        if tables.get(c).and_then(|t| t.get(n)) != Some(&Class::Local) { problems.push(format!("={l} in {BOUNDARY_FILE} names no node-local crate-root module")) }
    }
    let mut used = BTreeSet::new();
    checked.sort();
    for (file, krate, depth) in &checked {
        let own: BTreeSet<String> = tables.get(krate).map(|t| t.keys().cloned().collect()).unwrap_or_default();
        for (target, name) in references(&String::from_utf8_lossy(&files[file]), krate, *depth, &own) {
            if name == "*" { problems.push(format!("{file} glob-imports {target}::*; name the consensus items it uses")); continue }
            let q = format!("{target}::{name}");
            match tables.get(&target).and_then(|t| t.get(&name)) {
                Some(Class::Local) | Some(Class::Excluded) => {
                    if b.allow.iter().any(|(m, _)| *m == q) { used.insert(q); } else {
                        problems.push(format!("{file} (+) references {q}, which is node-local or excluded: add `~{q} <reason>` to {BOUNDARY_FILE} or make it +"))
                    }
                }
                _ => {}
            }
        }
    }
    for (m, _) in &b.allow { if !used.contains(m) { problems.push(format!("~{m} in {BOUNDARY_FILE} is unused; remove it")) } }
    problems
}

// ---- Cargo.lock dependency closure ----

#[derive(Clone, Debug, Default)]
struct Package { name: String, version: String, source: Option<String>, checksum: Option<String>, deps: Vec<String> }
fn packages(lock: &str) -> Result<Vec<Package>, Fail> {
    let mut out: Vec<Package> = Vec::new();
    let mut in_deps = false;
    let q = |v: &str| v.trim().trim_matches('"').to_string();
    for line in lock.lines() {
        let l = line.trim();
        if l == "[[package]]" { out.push(Package::default()); in_deps = false; continue }
        if l.starts_with('[') && !l.starts_with("[[package]]") && out.last().is_some() && !in_deps { return Err(format!("{CARGO_LOCK}: unexpected section {l}")) }
        let Some(p) = out.last_mut() else { continue };
        if in_deps { if l == "]" { in_deps = false } else if !l.is_empty() { p.deps.push(q(l.trim_end_matches(','))) } continue }
        if let Some((k, v)) = l.split_once(" = ") {
            match k { "name" => p.name = q(v), "version" => p.version = q(v), "source" => p.source = Some(q(v)), "checksum" => p.checksum = Some(q(v)),
                "dependencies" => { let v = v.trim(); if v == "[" { in_deps = true } else if v != "[]" { return Err(format!("{CARGO_LOCK}: inline dependency list")) } }
                _ => {} }
        }
    }
    if out.iter().any(|p| p.name.is_empty() || p.version.is_empty()) { return Err(format!("{CARGO_LOCK}: package without name or version")) }
    Ok(out)
}
/// `dep` lines (`name version source checksum`, `-` when absent) of every package reachable from a package named
/// by a root, sorted. An unresolvable or ambiguous dependency fails closed.
pub fn closure(lock: &str, roots: &[String]) -> Result<Vec<String>, Fail> {
    let pk = packages(lock)?;
    let resolve = |spec: &str| -> Result<usize, Fail> {
        let mut it = spec.split(' ');
        let name = it.next().unwrap_or(""); let version = it.next(); let source = it.next().map(|s| s.trim_matches(|c| c == '(' || c == ')'));
        let m: Vec<usize> = (0..pk.len()).filter(|&i| pk[i].name == name && version.map_or(true, |v| pk[i].version == v) && source.map_or(true, |s| pk[i].source.as_deref() == Some(s))).collect();
        if m.len() == 1 { Ok(m[0]) } else { Err(format!("{CARGO_LOCK}: dependency {spec:?} resolves to {} packages", m.len())) }
    };
    let mut stack = Vec::new();
    for r in roots {
        let m: Vec<usize> = (0..pk.len()).filter(|&i| pk[i].name == *r).collect();
        if m.is_empty() { return Err(format!("{CARGO_LOCK}: closure root {r} is not a package")) }
        stack.extend(m);
    }
    let mut seen = BTreeSet::new();
    while let Some(i) = stack.pop() {
        if !seen.insert(i) { continue }
        for d in &pk[i].deps { stack.push(resolve(d)?) }
    }
    let mut v: Vec<String> = seen.into_iter().map(|i| { let p = &pk[i]; format!("{} {} {} {}", p.name, p.version, p.source.as_deref().unwrap_or("-"), p.checksum.as_deref().unwrap_or("-")) }).collect();
    v.sort(); Ok(v)
}

