#[derive(Clone, Debug, PartialEq)]
pub struct History { pub n: u64, pub kind: String, pub rules: u64, pub max_fork: u64, pub spec: u64, pub protocol: u64, pub sources: String, pub vectors: String, pub deps: String, pub gate: Option<(String, u64)>, pub reference: String, pub note: String }
impl History {
    pub fn render(&self) -> String {
        let gate = self.gate.as_ref().map_or(String::new(), |(k, v)| format!(" gate={k}:{v}"));
        format!("history n={} kind={} rules={} maxFork={} spec={} protocol={} sources={} vectors={} deps={}{gate} ref={} note=\"{}\"",
            self.n, self.kind, self.rules, self.max_fork, self.spec, self.protocol, self.sources, self.vectors, self.deps, self.reference, self.note)
    }
}
#[derive(Clone, Debug, Default)]
pub struct Lock { pub history: Vec<History>, pub files: BTreeMap<String, String>, pub deps: Vec<String> }
fn parse_history(l: &str) -> Result<History, Fail> {
    let mut kv: BTreeMap<String, String> = BTreeMap::new();
    let mut rest = l.trim();
    while !rest.is_empty() {
        let (k, r) = rest.split_once('=').ok_or_else(|| format!("history field without '=': {rest}"))?;
        let (v, r) = if let Some(r) = r.strip_prefix('"') { let e = r.find('"').ok_or("unterminated note")?; (&r[..e], &r[e + 1..]) } else { r.split_once(' ').unwrap_or((r, "")) };
        if kv.insert(k.to_string(), v.to_string()).is_some() { return Err(format!("duplicate history field {k}")) }
        rest = r.trim_start();
    }
    let mut take = |k: &str| kv.remove(k).ok_or_else(|| format!("history line lacks {k}="));
    let num = |v: String, k: &str| v.parse::<u64>().map_err(|_| format!("history {k}={v} is not a number"));
    let h = History { n: num(take("n")?, "n")?, kind: take("kind")?, rules: num(take("rules")?, "rules")?, max_fork: num(take("maxFork")?, "maxFork")?, spec: num(take("spec")?, "spec")?,
        protocol: num(take("protocol")?, "protocol")?, sources: take("sources")?, vectors: take("vectors")?, deps: take("deps")?, gate: None, reference: take("ref")?, note: take("note")? };
    let gate = kv.remove("gate").map(|g| parse_gate(&g)).transpose()?;
    if let Some(k) = kv.keys().next() { return Err(format!("unknown history field {k}")) }
    Ok(History { gate, ..h })
}
pub fn parse_gate(g: &str) -> Result<(String, u64), Fail> {
    match g.split_once(':') {
        Some((k @ ("fork" | "spec"), v)) => Ok((k.to_string(), v.parse().map_err(|_| format!("gate {g}: not a number"))?)),
        _ => Err(format!("gate {g}: must be fork:V or spec:S")),
    }
}
pub fn parse_lock(text: &str) -> Result<Lock, Fail> {
    let mut lock = Lock::default();
    for (i, line) in text.lines().enumerate() {
        let l = line.trim_end();
        if l.is_empty() || l.starts_with('#') { continue }
        let err = |m: String| format!("{LOCK_FILE}:{}: {m}", i + 1);
        if let Some(h) = l.strip_prefix("history ") {
            // Only the canonical form is accepted, so a re-pin re-renders every earlier line byte for byte.
            let h = parse_history(h).map_err(err)?;
            if h.render() != l { return Err(err(format!("history line n={} is not in the form re-pin writes", h.n))) }
            lock.history.push(h)
        }
        else if let Some(f) = l.strip_prefix("file ") {
            let (sha, path) = f.split_once(' ').ok_or_else(|| err("file line needs <sha256> <path>".into()))?;
            if sha.len() != 64 || lock.files.insert(path.to_string(), sha.to_string()).is_some() { return Err(err(format!("bad or duplicate file line {path}"))) }
        } else if let Some(d) = l.strip_prefix("dep ") {
            if d.split(' ').count() != 4 { return Err(err("dep line needs <name> <version> <source> <checksum>".into())) }
            lock.deps.push(d.to_string())
        } else { return Err(err(format!("unknown lock line: {l}"))) }
    }
    lock.deps.sort();
    Ok(lock)
}
pub fn render_lock(history: &[History], t: &Tree) -> String {
    let mut s = String::from(LOCK_HEADER);
    for h in history { s += &h.render(); s.push('\n') }
    for (p, sha) in &t.files { s += &format!("file {sha} {p}\n") }
    for d in &t.deps { s += &format!("dep {d}\n") }
    s
}

/// The values a history line must agree with: identity::CONSENSUS_RULES_VERSION, profile::MAX_FORK_VERSION,
/// genesis_spec::SPEC_VERSION and identity::PROTOCOL_VERSION.
#[derive(Clone, Copy, Debug)]
pub struct Constants { pub rules: u64, pub max_fork: u64, pub spec: u64, pub protocol: u64 }

/// Guard check 3 (and 4): history consistency and the gate rule (plan §1.4).
pub fn history_problems(h: &[History], k: &Constants) -> Vec<String> {
    let mut e = Vec::new();
    let Some(last) = h.last() else { return vec!["the lock has no history line".into()] };
    for (i, x) in h.iter().enumerate() {
        let at = format!("history n={}", x.n);
        if x.n != i as u64 + 1 { e.push(format!("{at}: n must be {}", i + 1)) }
        if !KINDS.contains(&x.kind.as_str()) { e.push(format!("{at}: unknown kind {}", x.kind)) }
        if (i == 0) != (x.kind == "base") { e.push(format!("{at}: only the first line is kind=base")) }
        if x.note.trim().is_empty() || x.reference.trim().is_empty() { e.push(format!("{at}: kind={} needs a non-empty ref and note", x.kind)) }
        if x.gate.is_some() && x.kind != "neutral" { e.push(format!("{at}: a gate belongs only on kind=neutral")) }
        let Some(p) = i.checked_sub(1).map(|j| &h[j]) else { continue };
        if x.kind == "bump" && x.rules != p.rules + 1 { e.push(format!("{at}: bump must set rules={} (CONSENSUS_RULES_VERSION + 1)", p.rules + 1)) }
        if x.kind != "bump" && x.rules != p.rules { e.push(format!("{at}: kind={} must keep rules={} (only bump changes rules, and only with a new genesis)", x.kind, p.rules)) }
        if x.sources == p.sources { e.push(format!("{at}: sources repeat the previous line; nothing to record")) }
        if x.vectors != p.vectors && !["bump", "neutral-vector"].contains(&x.kind.as_str()) { e.push(format!("{at}: a vector file changed, so kind=neutral-vector (presumed bump) or bump is required, not {}", x.kind)) }
        if x.deps != p.deps && !["bump", "neutral-dep"].contains(&x.kind.as_str()) { e.push(format!("{at}: the dependency closure or a rust-toolchain.toml changed, so kind=neutral-dep (presumed bump) or bump is required, not {}", x.kind)) }
        if let Some((g, v)) = &x.gate {
            let spent = h[..i].iter().map(|y| if g == "fork" { y.max_fork } else { y.spec }).max().unwrap_or(0);
            if *v <= spent { e.push(format!("{at}: gate={g}:{v} is spent (an earlier line records {}={spent}; merged to main counts as released, D2)", if g == "fork" { "maxFork" } else { "spec" })) }
        }
    }
    if (last.rules, last.max_fork, last.spec, last.protocol) != (k.rules, k.max_fork, k.spec, k.protocol) {
        e.push(format!("last history line records rules={} maxFork={} spec={} protocol={}, but the code has CONSENSUS_RULES_VERSION={} MAX_FORK_VERSION={} SPEC_VERSION={} PROTOCOL_VERSION={}",
            last.rules, last.max_fork, last.spec, last.protocol, k.rules, k.max_fork, k.spec, k.protocol))
    }
    e
}

/// Guard checks 1–7 on a parsed lock and a computed tree. The error lists every finding, then the instructions.
pub fn check(lock: &Lock, t: &Tree, k: &Constants) -> Result<(), Fail> {
    let mut e = Vec::new();
    let vector = |p: &str| if t.vector_dirs.iter().any(|v| p.starts_with(v.as_str())) { " (VECTOR: neutral-vector, presumed bump)" } else if is_toolchain(p) { " (TOOLCHAIN: neutral-dep)" } else { "" };
    for (p, sha) in &t.files {
        let note = t.notes.get(p).map_or(String::new(), |n| format!(" [{n}]"));
        match lock.files.get(p) { None => e.push(format!("added: {p}{}{note}", vector(p))), Some(s) if s != sha => e.push(format!("changed: {p}{}{note}", vector(p))), _ => {} }
    }
    for p in lock.files.keys().filter(|p| !t.files.contains_key(*p)) { e.push(format!("removed: {p}{}", vector(p))) }
    let (now, was): (BTreeSet<&String>, BTreeSet<&String>) = (t.deps.iter().collect(), lock.deps.iter().collect());
    for d in now.difference(&was) { e.push(format!("dep added or changed (DEP: neutral-dep, presumed bump): {d}")) }
    for d in was.difference(&now) { e.push(format!("dep removed or changed (DEP: neutral-dep, presumed bump): {d}")) }
    if let Some(last) = lock.history.last() {
        if last.sources != t.sources { e.push(format!("the tree's consensus sources aggregate {} differs from the last history line's {}", t.sources, last.sources)) }
        if last.vectors != t.vectors || last.deps != t.dep_digest { e.push("the vector or dependency digest differs from the last history line".into()) }
    }
    e.extend(history_problems(&lock.history, k));
    e.extend(t.problems.iter().cloned());
    if e.is_empty() { Ok(()) } else { Err(format!("{}\n\n{INSTRUCTIONS}", e.join("\n"))) }
}

/// Re-pin mode: the new lock text with one appended history line (or, for `base`, a lock that does not exist on
/// main yet, the single base line), refused when the label cannot be right.
pub fn repin(lock: Option<&Lock>, t: &Tree, k: &Constants, kind: &str, reference: &str, note: &str, gate: Option<&str>) -> Result<String, Fail> {
    if !t.problems.is_empty() { return Err(format!("classify first:\n{}", t.problems.join("\n"))) }
    if !KINDS.contains(&kind) { return Err(format!("unknown kind {kind}; one of {KINDS:?}")) }
    for (n, v) in [("POCOL_REPIN_REF", reference), ("POCOL_REPIN_NOTE", note)] {
        if v.trim().is_empty() || v.contains('"') || v.contains('\n') { return Err(format!("{n} must be a non-empty single line without '\"'")) }
    }
    let gate = gate.map(parse_gate).transpose()?;
    let line = |n: u64, rules: u64| History { n, kind: kind.into(), rules, max_fork: k.max_fork, spec: k.spec, protocol: k.protocol, sources: t.sources.clone(), vectors: t.vectors.clone(),
        deps: t.dep_digest.clone(), gate: gate.clone(), reference: reference.into(), note: note.into() };
    let history = if kind == "base" {
        if lock.is_some_and(|l| l.history.len() > 1) { return Err("kind=base only creates a lock that has no appended lines yet".into()) }
        vec![line(1, k.rules)]
    } else {
        let l = lock.ok_or("no lock yet: the first line is kind=base")?;
        let last = l.history.last().ok_or("the lock has no history line")?;
        if t.sources == last.sources { return Err("the tree already matches the last history line; nothing to re-pin".into()) }
        let rules = if kind == "bump" { last.rules + 1 } else { last.rules };
        if k.rules != rules { return Err(format!("kind={kind} needs CONSENSUS_RULES_VERSION = {rules} in pocold/src/identity.rs (it is {})", k.rules)) }
        if kind == "neutral" && t.vectors != last.vectors { return Err("a vector file changed: kind=neutral is refused; use neutral-vector (presumed bump) or bump".into()) }
        if kind == "neutral" && t.dep_digest != last.deps { return Err("the dependency closure or a toolchain changed: kind=neutral is refused; use neutral-dep (presumed bump) or bump".into()) }
        let mut h = l.history.clone(); h.push(line(last.n + 1, rules)); h
    };
    let text = render_lock(&history, t);
    check(&parse_lock(&text)?, t, k).map(|_| text)
}

/// `const NAME: T = <digits>;` in a source file (build.rs reads the constants it reports in build-info).
pub fn const_u64(src: &str, name: &str) -> Option<u64> {
    let s = strip_comments(src);
    let i = s.find(&format!("const {name}:"))?;
    let v = s[i..].split_once('=')?.1.split_once(';')?.0.trim().replace('_', "");
    v.parse().ok()
}
