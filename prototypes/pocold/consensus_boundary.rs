pub type Fail = String;

/// Parsed consensus-boundary.txt.
#[derive(Clone, Debug, Default)]
pub struct Boundary { pub include: Vec<String>, pub exclude: Vec<String>, pub suffix: Vec<String>, pub local: Vec<String>, pub allow: Vec<(String, String)>, pub roots: Vec<String>, pub vectors: Vec<String> }
fn safe_path(p: &str) -> Result<(), Fail> {
    if p.is_empty() || p.starts_with('/') || p.contains('\\') || p.split('/').any(|c| c == ".." || c == ".") || p.contains("//") { return Err(format!("unsafe boundary path {p:?}")) }
    Ok(())
}
fn module_name(m: &str) -> Result<(), Fail> {
    match m.split_once("::") {
        Some((c, n)) if CRATES.iter().any(|x| x.0 == c) && !n.is_empty() && n.chars().all(|ch| ch.is_ascii_alphanumeric() || ch == '_') => Ok(()),
        _ => Err(format!("boundary module {m:?} must be <crate>::<module> with crate pocold or lp4")),
    }
}
/// `+a/{b,c}.rs` expands to `+a/b.rs` and `+a/c.rs` (one group per line).
fn expand(p: &str) -> Vec<String> {
    match (p.find('{'), p.find('}')) {
        (Some(a), Some(b)) if a < b => p[a + 1..b].split(',').map(|x| format!("{}{}{}", &p[..a], x.trim(), &p[b + 1..])).collect(),
        _ => vec![p.to_string()],
    }
}
pub fn parse_boundary(text: &str) -> Result<Boundary, Fail> {
    let mut b = Boundary::default();
    for (i, raw) in text.lines().enumerate() {
        let line = raw.trim();
        if line.is_empty() || line.starts_with('#') { continue }
        let err = |m: &str| format!("{BOUNDARY_FILE}:{}: {m}: {line}", i + 1);
        if let Some(p) = line.strip_prefix('+') {
            for p in expand(p.trim()) { safe_path(&p).map_err(|e| err(&e))?; b.include.push(p) }
        } else if let Some(p) = line.strip_prefix("-*") {
            if p.is_empty() || p.contains('/') { return Err(err("a suffix exclusion names a file-name suffix")) }
            b.suffix.push(p.to_string())
        } else if let Some(p) = line.strip_prefix('-') {
            for p in expand(p.trim()) { safe_path(&p).map_err(|e| err(&e))?; b.exclude.push(p) }
        } else if let Some(m) = line.strip_prefix('=') {
            module_name(m.trim()).map_err(|e| err(&e))?; b.local.push(m.trim().to_string())
        } else if let Some(rest) = line.strip_prefix('~') {
            let (m, why) = rest.split_once(' ').ok_or_else(|| err("an allowed reference needs a reason"))?;
            module_name(m).map_err(|e| err(&e))?;
            if why.trim().is_empty() { return Err(err("an allowed reference needs a reason")) }
            b.allow.push((m.to_string(), why.trim().to_string()))
        } else if let Some(r) = line.strip_prefix("root ") {
            b.roots.push(r.trim().to_string())
        } else if let Some(v) = line.strip_prefix("vector ") {
            let v = v.trim(); safe_path(v).map_err(|e| err(&e))?;
            if !v.ends_with('/') { return Err(err("a vector directory ends with /")) }
            b.vectors.push(v.to_string())
        } else {
            return Err(err("unknown line kind"))
        }
    }
    if b.include.is_empty() || b.roots.is_empty() { return Err(format!("{BOUNDARY_FILE}: no includes or no closure roots")) }
    Ok(b)
}
fn covers(rule: &str, path: &str) -> bool { if rule.ends_with('/') { path.starts_with(rule) } else { path == rule } }

/// Every regular file under `dir` (relative, ends with '/'), sorted. Symlinks are refused.
fn walk(root: &Path, dir: &str, out: &mut Vec<String>) -> Result<(), Fail> {
    let mut names = Vec::new();
    for entry in std::fs::read_dir(root.join(dir)).map_err(|e| format!("{dir}: {e}"))? {
        let entry = entry.map_err(|e| format!("{dir}: {e}"))?;
        let name = entry.file_name().into_string().map_err(|_| format!("{dir}: non-UTF-8 file name"))?;
        names.push((name, entry.file_type().map_err(|e| format!("{dir}: {e}"))?));
    }
    names.sort_by(|a, b| a.0.cmp(&b.0));
    for (name, ty) in names {
        if ty.is_symlink() { return Err(format!("{dir}{name}: symlinks are not supported in the consensus boundary")) }
        if ty.is_dir() { walk(root, &format!("{dir}{name}/"), out)? } else { out.push(format!("{dir}{name}")) }
    }
    Ok(())
}

/// The computed side: manifest, dependency closure, aggregates and classification problems.
#[derive(Clone, Debug, Default)]
pub struct Tree {
    pub files: BTreeMap<String, String>,
    pub deps: Vec<String>,
    pub sources: String,
    pub vectors: String,
    pub dep_digest: String,
    pub vector_dirs: Vec<String>,
    /// Reasons a `-*suffix` file is nevertheless in the manifest (guard check 7).
    pub notes: BTreeMap<String, String>,
    /// Guard checks 5–7: unclassified modules, references into `=`/`-` modules, unused allowances.
    pub problems: Vec<String>,
    /// Every boundary file and walked directory, for `cargo:rerun-if-changed`.
    pub watched: Vec<String>,
}
fn hex(b: &[u8]) -> String { b.iter().map(|x| format!("{x:02x}")).collect() }
pub fn sha256_hex(b: &[u8]) -> String { hex(&Sha256::digest(b)) }
/// SHA256(domain ‖ (u64 len name ‖ name ‖ u64 len bytes ‖ bytes)*) over entries sorted by name.
pub fn aggregate<'a>(domain: &[u8], entries: impl IntoIterator<Item = (&'a str, &'a [u8])>) -> String {
    let mut e: Vec<(&str, &[u8])> = entries.into_iter().collect();
    e.sort_by(|a, b| a.0.cmp(b.0));
    let mut h = Sha256::new();
    h.update(domain);
    for (name, bytes) in e {
        h.update((name.len() as u64).to_be_bytes()); h.update(name.as_bytes());
        h.update((bytes.len() as u64).to_be_bytes()); h.update(bytes);
    }
    hex(&h.finalize())
}
/// rust-toolchain.toml files count with the dependency closure (`neutral-dep`, plan §1.4).
pub fn is_toolchain(path: &str) -> bool { path.rsplit('/').next() == Some("rust-toolchain.toml") }

pub fn compute(root: &Path) -> Result<Tree, Fail> {
    let text = std::fs::read_to_string(root.join(BOUNDARY_FILE)).map_err(|e| format!("{BOUNDARY_FILE}: {e}"))?;
    let lock = std::fs::read_to_string(root.join(CARGO_LOCK)).map_err(|e| format!("{CARGO_LOCK}: {e}"))?;
    compute_with(root, &parse_boundary(&text)?, &lock)
}
pub fn compute_with(root: &Path, b: &Boundary, cargo_lock: &str) -> Result<Tree, Fail> {
    let mut t = Tree { vector_dirs: b.vectors.clone(), ..Tree::default() };
    let mut candidates = BTreeSet::new();
    for inc in &b.include {
        if inc.ends_with('/') {
            let mut v = Vec::new(); walk(root, inc, &mut v)?; candidates.extend(v); t.watched.push(inc.clone());
        } else {
            if !root.join(inc).is_file() { return Err(format!("boundary file {inc} does not exist")) }
            candidates.insert(inc.clone());
        }
    }
    for v in &b.vectors { if !b.include.iter().any(|i| covers(i, v) || i == v) { return Err(format!("vector directory {v} is not included")) } }
    let mut bytes: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    let mut test_only = BTreeSet::new();
    for path in candidates {
        if b.exclude.iter().any(|x| covers(x, &path)) { continue }
        if let Some(s) = b.suffix.iter().find(|s| path.ends_with(s.as_str())) {
            match declared_only_under_cfg_test(root, &path) {
                Ok(()) => { test_only.insert(path); continue }
                Err(why) => { t.notes.insert(path.clone(), format!("matches -*{s} but {why}, so it is treated as consensus (+)")); }
            }
        }
        let data = std::fs::read(root.join(&path)).map_err(|e| format!("{path}: {e}"))?;
        t.files.insert(path.clone(), sha256_hex(&data));
        bytes.insert(path, data);
    }
    t.deps = closure(cargo_lock, &b.roots)?;
    let closure_bytes: String = t.deps.iter().map(|d| format!("dep {d}\n")).collect();
    let all = bytes.iter().map(|(n, d)| (n.as_str(), d.as_slice())).chain([(CLOSURE_NAME, closure_bytes.as_bytes())]);
    t.sources = aggregate(b"pocol-consensus-sources-v1\0", all);
    t.vectors = aggregate(b"pocol-consensus-vectors-v1\0", bytes.iter().filter(|(n, _)| b.vectors.iter().any(|v| n.starts_with(v.as_str()))).map(|(n, d)| (n.as_str(), d.as_slice())));
    t.dep_digest = aggregate(b"pocol-consensus-deps-v1\0", bytes.iter().filter(|(n, _)| is_toolchain(n)).map(|(n, d)| (n.as_str(), d.as_slice())).chain([(CLOSURE_NAME, closure_bytes.as_bytes())]));
    t.problems = modules(root, b, &bytes, &test_only);
    t.watched.extend(bytes.keys().cloned());
    Ok(t)
}

